//! # `nt-syscall-abi` — the shared Nt*/Zw* SSN ABI table
//!
//! The **single source of truth** for the mapping between an `Nt*`/`Zw*` export name and its
//! **system-service number (SSN)**, shared between our Rust ntdll ([`crate`] consumers in
//! `nt-ntdll`) and the NT executive that services the calls.
//!
//! ## Why this crate exists (the SSN-collision dissolution)
//!
//! Historically each Windows version's *own* `ntdll` baked in its *own* SSN table, and those
//! tables collide (Win7 `NtAlpcConnectPort` = 113 collides with ReactOS `NtMapViewOfSection`
//! = 113). Because import resolution against ntdll is **by name** (`NtCreateFile` resolves
//! through ntdll's export; the SSN is an *internal* detail of the stub), owning ntdll makes the
//! SSN **our** free choice. We fix it ONCE, here, and both ends agree.
//!
//! ## Ground truth: the ReactOS `sysfuncs.lst` numbering (do NOT renumber)
//!
//! The SSN numbering is **`references/reactos/ntoskrnl/sysfuncs.lst`-derived**: the SSN of an
//! `Nt*` service is its **0-based line index** in that file. This is *exactly* the numbering the
//! NT executive already dispatches on (`components/ntos-executive` `SSN_NT_*` consts). Reusing it
//! is what makes owning ntdll **zero-churn on the executive** — the executive keeps dispatching
//! unchanged. Verified anchors (asserted in the tests): `NtClose = 27`, `NtCreateFile = 39`,
//! `NtOpenFile = 122`, `NtProtectVirtualMemory = 143`, `NtAllocateVirtualMemory = 18`, …
//!
//! ## The ALPC seam
//!
//! ReactOS implements no `NtAlpc*` service. LiberNT SMSS imports ALPC calls, so our ntdll
//! assigns them private SSNs above the legacy range. These numbers are internal to our
//! ntdll/executive pair, independent of the released LiberNT ntdll's numbering.
//!
//! `no_std`, pure data — every table is `const`; the whole thing is host-testable.

#![no_std]

pub mod native_context;
pub use native_context::NT_NATIVE_CONTEXT_SYSCALL_LABEL;

/// A single `Nt*` service's ABI entry: its canonical export name and its SSN.
#[derive(Copy, Clone, Debug, PartialEq, Eq)]
pub struct NtSyscall {
    /// The canonical `Nt*` export name (e.g. `"NtCreateFile"`).
    pub name: &'static str,
    /// The system-service number (the immediate baked into the ntdll stub's `mov eax, <ssn>`).
    /// = the 0-based line index of this service in ReactOS `ntoskrnl/sysfuncs.lst`.
    pub ssn: u32,
}

/// A `Zw*` export that is an alias of an `Nt*` service (same SSN, kernel-previous-mode semantics).
#[derive(Copy, Clone, Debug, PartialEq, Eq)]
pub struct ZwAlias {
    /// The `Zw*` export name.
    pub zw_name: &'static str,
    /// The underlying `Nt*` service name it aliases.
    pub nt_name: &'static str,
    /// The shared SSN.
    pub ssn: u32,
}

/// Base SSN for the ALPC surface implemented by our native ntdll/executive pair.
///
/// ReactOS `sysfuncs.lst` tops out at SSN 295. This range also stays below 0x1000, where the
/// executive routes GUI clients into the win32k shadow table after native-call normalization.
/// Native code imports ntdll by export name, leaving this numbering under our control.
pub const ALPC_SSN_BASE: u32 = 0x700;

/// Private service-number range for the additional native exports imported by the pinned
/// LiberNT kernel32.dll and advapi32.dll. These names have no ReactOS sysfuncs.lst number;
/// this range is internal to our ntdll/executive pair and is never LiberNT's own numbering.
/// It must remain below 0x1000: the executive routes service numbers at or above 0x1000 into
/// the win32k shadow table for GUI clients, including native calls after receive normalization.
pub const LIBERNT_BASE_SSN: u32 = 0x300;

/// Reserved native SSNs for the remaining pinned LiberNT ntdll syscall export names.
/// These stay below the executive's 0x1000 win32k shadow-table routing boundary.
pub const LIBERNT_FULL_EXPORT_SSN_BASE: u32 = 0x400;

/// ntdll_plan Step 6.A — the msginfo LABEL that marks a REQUEST as an NT native seL4-Call syscall
/// (our ntdll's `Nt*` stub → the executive over a real seL4 `Call`, NOT a Windows-`syscall`
/// UnknownSyscall trap). ASCII `"NT"` (0x4E54) — well clear of the kernel fault-type labels
/// (`UnknownSyscall`=2, `UserException`=3, `VMFault`=6), so the executive's service loop tells a
/// native-syscall message from a fault message by `mi>>12`. The single source of truth shared by OUR
/// ntdll (the stub side) and the executive (the recv side). See `nt_ntdll::native_call` for the full
/// wire layout (MR0=SSN, MR1=rsp, MR2..=argc+1=args; reply MR0=NTSTATUS).
pub const NT_NATIVE_SYSCALL_LABEL: u64 = 0x4E54;

/// Fixed words before the native syscall argument vector.
pub const NT_NATIVE_SYSCALL_PREFIX_WORDS: u64 = 2;

/// Exact native-call request length for a service with `argc` arguments.
pub const fn native_syscall_request_len(argc: u8) -> u64 {
    NT_NATIVE_SYSCALL_PREFIX_WORDS + argc as u64
}

/// seL4 message-info word for an exact native syscall request.
pub const fn native_syscall_message_info(argc: u8) -> u64 {
    (NT_NATIVE_SYSCALL_LABEL << 12) | native_syscall_request_len(argc)
}

/// The largest native request emitted by the generated NT stubs (two prefix words and up to
/// seventeen arguments). Capture these words before the receiver performs any nested IPC.
pub const NT_NATIVE_REQUEST_WORDS: usize =
    NT_NATIVE_SYSCALL_PREFIX_WORDS as usize + MAX_STUB_ARGS as usize;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct NativeSyscallRequest {
    length: usize,
    words: [u64; NT_NATIVE_REQUEST_WORDS],
}

impl NativeSyscallRequest {
    /// Fast message registers are passed by value; `read_tail` reads MR4 and later from the
    /// current receive. No caller may use the mutable IPC buffer as the request after this call.
    pub fn capture(
        info: u64,
        registers: [u64; 4],
        mut read_tail: impl FnMut(usize) -> u64,
    ) -> Option<Self> {
        if info >> 12 != NT_NATIVE_SYSCALL_LABEL {
            return None;
        }
        let length = (info & 0x7f) as usize;
        let mut words = [0; NT_NATIVE_REQUEST_WORDS];
        for index in 0..length.min(NT_NATIVE_REQUEST_WORDS) {
            words[index] = if index < registers.len() {
                registers[index]
            } else {
                read_tail(index)
            };
        }
        Some(Self { length, words })
    }

    pub const fn length(&self) -> usize {
        self.length
    }

    pub fn word(&self, index: usize) -> Option<u64> {
        (index < self.length).then(|| self.words.get(index).copied()).flatten()
    }

    pub fn argument(&self, index: usize) -> Option<u64> {
        index.checked_add(NT_NATIVE_SYSCALL_PREFIX_WORDS as usize)
            .and_then(|word| self.word(word))
    }
}

/// Private executive-to-ntdll reply marker requesting that a parked native seL4-Call syscall be
/// reissued with the restored request MRs. It is deliberately outside the 32-bit NTSTATUS domain.
pub const NT_NATIVE_RETRY_REPLY: u64 = 0x4E54_5254_5259_0001;

/// Resume coordinates retained for deferred syscall and callback handling.
///
/// These coordinates are metadata, not a register restore image. Ordinary completion sends only
/// the terminal status through the retained Reply capability, preserving canonical TCB state.
#[derive(Copy, Clone, Debug, PartialEq, Eq)]
pub struct ParkedSyscallReply {
    resume: [u64; 3],
}

impl Default for ParkedSyscallReply {
    fn default() -> Self {
        Self::native_call()
    }
}

impl ParkedSyscallReply {
    /// Retain an ordinary native seL4-Call continuation.
    pub const fn native_call() -> Self {
        Self {
            resume: [0; 3],
        }
    }

    /// Retain a hosted x86-64 UnknownSyscall continuation.
    pub const fn unknown_syscall(
        resume_ip: u64,
        resume_sp: u64,
        resume_flags: u64,
    ) -> Self {
        Self {
            resume: [resume_ip, resume_sp, resume_flags],
        }
    }

    /// Saved user instruction pointer for a hosted UnknownSyscall continuation.
    pub const fn resume_ip(self) -> u64 {
        self.resume[0]
    }

    /// Saved user stack pointer for a hosted UnknownSyscall continuation.
    pub const fn resume_sp(self) -> u64 {
        self.resume[1]
    }

    /// Saved user flags for a hosted UnknownSyscall continuation.
    pub const fn resume_flags(self) -> u64 {
        self.resume[2]
    }
}

/// TEB VA used by the SEC_IMAGE hosted-process main thread.
///
/// Native syscall stubs read this value through the standard x64 `gs:[0x30]` TEB self pointer.
pub const NT_NATIVE_SEC_IMAGE_MAIN_TEB_VA: u64 = 0x0000_0100_1600_0000;

/// TEB VA used by the older isolated-PE main-thread path.
pub const NT_NATIVE_PE_MAIN_TEB_VA: u64 = 0x0000_0100_0057_0000;

/// IPC-buffer VA shared by the two main-thread layouts (in their separate VSpaces).
pub const NT_NATIVE_MAIN_IPC_BUFFER_VA: u64 = 0x0000_0100_105F_B000;

/// Distance between a hosted worker's TEB and its dedicated IPC-buffer mapping.
pub const NT_NATIVE_WORKER_IPC_BUFFER_DELTA: u64 = 0x0001_0000;

/// Select the native seL4 IPC-buffer VA for the thread whose TEB is at `teb`.
///
/// The two historical main-thread layouts retain their fixed IPC-buffer VA. Runtime workers use
/// dedicated buffers one 64-KiB allocation unit below their TEB, so concurrent native calls cannot
/// overwrite another thread's MR4/MR5 spill words.
#[inline]
pub const fn native_ipc_buffer_va(teb: u64) -> u64 {
    if teb == NT_NATIVE_SEC_IMAGE_MAIN_TEB_VA || teb == NT_NATIVE_PE_MAIN_TEB_VA {
        NT_NATIVE_MAIN_IPC_BUFFER_VA
    } else {
        teb - NT_NATIVE_WORKER_IPC_BUFFER_DELTA
    }
}

